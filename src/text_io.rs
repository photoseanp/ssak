use std::path::Path;

/// Считывает текстовый файл с lossy-UTF8-декодированием.
///
/// Экспортные файлы легаси-инструмента Palace/TSI (`*.txt`, `*.pal`)
/// сохраняются в однобайтовой кодировке Windows (кириллица в
/// rem.1/rem.2, символы единиц измерения °, µ, ², ³), а не в UTF-8, поэтому
/// `fs::read_to_string` возвращает ошибку и файл тихо пропускается. Все
/// значимые для парсинга токены — заголовки колонок (P_diff, main air,
/// X, E, l/min) и числа — состоят только из ASCII-символов, которые
/// совпадают в любой однобайтовой кодировке, поэтому lossy-декодирование
/// (замена нераспознанных байт на U+FFFD) даёт корректный результат без
/// определения конкретной кодировки и без внешних зависимостей.
pub fn read_text_lossy(path: &Path) -> Option<String> {
    let bytes = std::fs::read(path).ok()?;
    Some(String::from_utf8_lossy(&bytes).into_owned())
}
